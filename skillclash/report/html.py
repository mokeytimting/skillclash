def _js(data: object) -> str:
    """JSON safe for embedding inside <script>."""
    return (
        json.dumps(data, ensure_ascii=False)
        .replace("<", "\\u003c")
        .replace(">", "\\u003e")
        .replace("&", "\\u0026")
    )


def generate_html_report(scan_result: ScanResult, lang: str = "zh-TW") -> str:
    """Generate a single-file, offline-capable, responsive HTML report."""
    L = LABELS.get(lang, LABELS["en"])
    units = scan_result.units
    findings = scan_result.findings
    stats = scan_result.stats

    all_skills: list[Skill] = [sk for u in units for sk in u.skills]
    total_tokens = sum(estimate_listing_tokens(sk) for sk in all_skills if sk.model_invocable)

    active = [f for f in findings if not f.suppressed_by]
    err_count = sum(1 for f in active if f.severity == Severity.ERROR)
    warn_count = sum(1 for f in active if f.severity == Severity.WARN)
    info_count = sum(1 for f in active if f.severity == Severity.INFO)

    findings_data = [
        {
            "rule": f.rule,
            "severity": f.severity.value,
            "title": f.title,
            "message": f.message,
            "skills": [
                {
                    "name": s.qualified_name or s.name,
                    "unit_id": s.unit_id,
                    "path": s.path,
                    "line": s.line,
                    "quote": s.quote,
                }
                for s in f.skills
            ],
            "fix": f.fix,
            "suppressed_by": f.suppressed_by,
        }
        for f in sorted(findings, key=lambda f: (["error", "warn", "info"].index(f.severity.value), f.rule))
    ]

    unit_rows = []
    for u in units:
        u_tokens = sum(estimate_listing_tokens(sk) for sk in u.skills if sk.model_invocable)
        inferred_badge = (
            f" <span class='badge badge-inferred'>{html.escape(L['inferred'])}</span>" if u.inferred else ""
        )
        unit_rows.append(
            "<tr>"
            f"<td><code>{html.escape(u.id)}</code>{inferred_badge}</td>"
            f"<td>{html.escape(u.label)}</td>"
            f"<td>{len(u.skills)}</td>"
            f"<td>~{u_tokens:,}</td>"
            f"<td><code>{html.escape(display_origin(u.origin))}</code></td>"
            "</tr>"
        )

    # Precomputed so the f-string below stays valid on Python 3.11 (no nested quotes).
    labels_js = _js(L)
    findings_js = _js(findings_data)
    clusters_js = _js(stats.get("overlap_clusters", []))
    route_js = _js(stats.get("route_matrix", {}))
    unit_rows_html = "".join(unit_rows)
    E = {k: html.escape(v) for k, v in L.items()}
    generated = html.escape(L["generated"].format(version=skillclash.__version__))

