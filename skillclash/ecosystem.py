def load_packs(config_path: Path) -> list[dict[str, Any]]:
    """Load packs definition from TOML file."""
    if not config_path.is_file():
        return []
    with open(config_path, "rb") as f:
        return tomllib.load(f).get("packs", [])


def _page(title: str, body: str) -> str:
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{html.escape(title)}</title>
<style>{_STYLE}</style>
</head>
<body><div class="container">
<header>
  <h1>{html.escape(title)}</h1>
  <p class="muted">Conflicts between popular Agent Skills packs · 熱門 Agent Skills 包之間的衝突</p>
  <nav><a href="index.html">Conflict matrix 衝突矩陣</a><a href="repack.html">Shared skills 重複收錄</a></nav>
</header>
{body}
<p class="muted" style="font-size:0.8rem;">Generated by skillclash {html.escape(skillclash.__version__)} · {html.escape(skillclash.REPO_URL)}</p>
</div></body></html>"""


def build_ecosystem_site(packs_file: str | Path, output_dir: str | Path, offline: bool = False) -> int:
    """Build the static ecosystem site with a pack x pack conflict matrix and a shared-skill table."""
    packs = load_packs(Path(packs_file))
    if not packs:
        print(f"No packs found in {packs_file}", file=sys.stderr)
        return 2
    out_dir = Path(output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    pack_names = [p["name"] for p in packs]
    unit_to_pack: dict[str, str] = {}
    all_units = []
    for p in packs:
        units, stats = resolve_sources([p["origin"]], offline=offline)
        for err in stats["fetch_errors"]:
            print(f"warning: {err[0]}: {err[1]}", file=sys.stderr)
        for u in units:
            u.pack = p["name"]
            unit_to_pack[u.id] = p["name"]
            all_units.append(u)

    print(f"Analyzing {sum(len(u.skills) for u in all_units)} skills from {len(packs)} packs...")
    findings, _ = run_analyzers(all_units, {}, lang="en")

    idx = {name: i for i, name in enumerate(pack_names)}
    n = len(pack_names)
    matrix = [[0] * n for _ in range(n)]
    details: dict[str, list[dict[str, Any]]] = {}
    shared: list[dict[str, Any]] = []

    for f in findings:
        if f.rule not in PAIR_RULES or len(f.skills) < 2:
            continue
        pa, pb = unit_to_pack.get(f.skills[0].unit_id), unit_to_pack.get(f.skills[1].unit_id)
        if not pa or not pb or pa == pb:
            continue
        i, j = sorted((idx[pa], idx[pb]))
        matrix[i][j] += 1
        matrix[j][i] += 1
        details.setdefault(f"{i}_{j}", []).append({
            "rule": f.rule,
            "severity": f.severity.value,
            "title": f.title,
            "message": f.message,
        })
        if f.rule == "NAME-CLASH" and f.evidence.get("variant") in ("identical", "drifted"):
            shared.append({
                "skill": f.skills[0].name,
                "a": pa,
                "b": pb,
                "variant": f.evidence["variant"],
                "similarity": f.evidence.get("jaccard"),
            })

    data_js = _js({"packs": pack_names, "matrix": matrix, "details": details})
    matrix_body = f"""
<div class="card"><table id="matrix"></table></div>
<div class="card" id="detail"><p class="muted">Click a number to list the findings. 點數字查看細節。</p></div>
<script>
const data = {data_js};
function esc(s) {{ return String(s ?? "").replace(/[&<>'"]/g, c => ({{"&":"&amp;","<":"&lt;",">":"&gt;","'":"&#39;",'"':"&quot;"}}[c])); }}
const max = Math.max(1, ...data.matrix.flat());
let h = "<tr><th></th>" + data.packs.map((p, i) => `<th title="${{esc(p)}}">#${{i + 1}}</th>`).join("") + "</tr>";
data.packs.forEach((p, i) => {{
  h += `<tr><th class="row">#${{i + 1}} ${{esc(p)}}</th>`;
  data.packs.forEach((_, j) => {{
    if (i === j) {{ h += "<td class='muted'>–</td>"; return; }}
    const v = data.matrix[i][j];
    h += `<td style="background:rgba(var(--hot), ${{(v / max * 0.7).toFixed(2)}})"><button class="cell" data-i="${{i}}" data-j="${{j}}">${{v}}</button></td>`;
  }});
  h += "</tr>";
}});
document.getElementById("matrix").innerHTML = h;
document.getElementById("matrix").addEventListener("click", e => {{
  const b = e.target.closest("button.cell"); if (!b) return;
  const i = +b.dataset.i, j = +b.dataset.j;
  const items = data.details[Math.min(i, j) + "_" + Math.max(i, j)] || [];
  document.getElementById("detail").innerHTML =
    `<h3>${{esc(data.packs[i])}} ↔ ${{esc(data.packs[j])}} (${{items.length}})</h3><br>` +
    items.map(it => `<div class="item"><b>[${{esc(it.severity.toUpperCase())}}] ${{esc(it.title)}}</b><div class="muted" style="white-space:pre-wrap">${{esc(it.message)}}</div></div>`).join("");
}});
</script>"""
    (out_dir / "index.html").write_text(_page("Agent Skills ecosystem map", matrix_body), encoding="utf-8")

    rows = "".join(
        "<tr>"
        f"<td class='left'><code>{html.escape(s['skill'])}</code></td>"
        f"<td class='left'>{html.escape(s['a'])}</td>"
        f"<td class='left'>{html.escape(s['b'])}</td>"
        f"<td>{html.escape(s['variant'])}</td>"
        f"<td>{s['similarity']}</td>"
        "</tr>"
        for s in sorted(shared, key=lambda s: (s["skill"], s["a"], s["b"]))
    )
    repack_body = (
        "<div class='card'><p class='muted' style='margin-bottom:0.75rem;'>Skills with the same name in two packs "
        "whose bodies are identical or drifted copies (Jaccard ≥ 0.5). 兩個包中同名、內容相同或相近的 skill。</p>"
        "<table><thead><tr><th class='left'>Skill</th><th class='left'>Pack A</th><th class='left'>Pack B</th>"
        f"<th>Variant</th><th>Similarity</th></tr></thead><tbody>{rows}</tbody></table></div>"
    )
    (out_dir / "repack.html").write_text(_page("Shared skills between packs", repack_body), encoding="utf-8")
    print(f"Ecosystem site written to {out_dir}")
    return 0
