import skillclash
from skillclash.analyzers import run_analyzers
from skillclash.report.html import _js
from skillclash.sources import resolve_sources

PAIR_RULES = ("NAME-CLASH", "DUP-CONTENT", "OVERLAP", "RULE-CONFLICT")

